Contains
    
    Subroutine DestroyField (self)
        Implicit None
        Class (FieldGeometry), Intent (InOut) :: self
        
        if (ALLOCATED(self%cutout))   DEALLOCATE(self%cutout)
        if (ALLOCATED(self%angdist))  DEALLOCATE(self%angdist)
        if (ALLOCATED(self%spectrum)) DEALLOCATE(self%spectrum)
        
    End Subroutine
    
    Subroutine DestroyBeam (self)
        Implicit None
        Class (ExternalBeam), Intent (InOut) :: self
        
        if (ALLOCATED(self%quadmask)) DEALLOCATE(self%quadmask)
        if (ALLOCATED(self%elemmask)) DEALLOCATE(self%elemmask)
        if (ALLOCATED(self%particle)) DEALLOCATE(self%particle)
        if (ALLOCATED(self%phi0s))    DEALLOCATE(self%phi0s)
        if (ASSOCIATED(self%mesh))    NULLIFY(self%mesh)
        if (ASSOCIATED(self%angular)) NULLIFY(self%angular)
        call self%fldgeo%Destroy ()
        if (ALLOCATED(self%rays))     DEALLOCATE(self%rays)
        
    End Subroutine
    
    Subroutine InitializeLegendreCoefficients (L)
        use Polynomials
        Implicit None
        Integer, Intent (In) :: L
        
        Lcoeff = L
        call LegendreCoefficients (L, coeff)
        
    End Subroutine
    
    Subroutine DestroyLegendreCoefficients ()
        Implicit None
        
        Lcoeff = 0
        DEALLOCATE(coeff)
        
    End Subroutine
    
    Function GenAngularDistribution (k, k0) Result (f)
        use BasicMathFunctions
        use Polynomials
        Implicit None
        Real (KREAL), Intent (In) :: k  (3)
        Real (KREAL), Intent (In) :: k0 (3)
        
        Real (KREAL)              :: f
        
        Integer                   :: ell
        Real (KREAL)              :: kk0
        
        kk0 = DOT_PRODUCT(k, k0)
        
        f = ZERO
        do ell = 0, Lcoeff
            f = f + (2 * ell + 1) * SimpleHorner (x=kk0, c=coeff(ell,0:ell)) / FOURPI
        end do
        
    End Function
    
    Function SlabAngularDistribution (mu, mu0) Result (f)
        use BasicMathFunctions
        use Polynomials
        Implicit None
        Real (KREAL), Intent (In) :: mu
        Real (KREAL), Intent (In) :: mu0
        
        Real (KREAL)              :: f
        
        Integer                   :: ell
        
        f = ZERO
        do ell = 0, Lcoeff
            f = f + HALF * (2 * ell + 1) * SimpleHorner (x=mu, c=coeff(ell,0:ell)) * SimpleHorner (x=mu0, c=coeff(ell,0:ell))
        end do
        
    End Function
    
