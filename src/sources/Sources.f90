    Type FieldGeometry
        ! This class defines the abstract geometric character of a beam, 
        ! independent of the problem discretization.
        ! 
        ! Contains InField, which, if given a point r,
        ! it tells you whether or not the point is in the beam
        Logical                        :: slab               ! Whether or not this is a slab-based source
        Real (KREAL)                   :: weight             ! Scaling factor for the particles in the beam. Beam units are generally in 'per particle' but with multiple beams you must scale them relatively using this
        Real (KREAL)                   :: span               ! Either the area of the field cross section (for planar beams) or the solid angle (for spherical beams)
        Real (KREAL)                   :: origin       (3)   ! Origin of the incident field (important if angular = spherical)
        Real (KREAL)                   :: axis         (3)   ! Central axis of the incident field, direction describing the direction of particles.
        Real (KREAL)                   :: e1           (3)   ! Beam-frame x vector
        Real (KREAL)                   :: e2           (3)   ! Beam-frame y vector
        Real (KREAL)                   :: cutoutparams (4)   ! Linac cutout parameters ! MAY NOT BE NEEDED OUTSIDE OF INPUT, KEEPING IN CASE I DO SOME STUFF WITH MANUALLY FINDING NODES IN BEAM
        Character (LEN=:), Allocatable :: cutout             ! Field cutout shape (none, circle, rectangle). Later on users will be able to enter a filename with a 2D loop described by mesh points
        Character (LEN=:), Allocatable :: angdist            ! Angular distribution of field ('spherical', 'planar')
        Character (LEN=:), Allocatable :: spectrum           ! A file (OR the string 'flat') specifying what the field's energy spectrum is
    Contains
        Procedure :: InField
        Procedure :: Destroy => DestroyField
    End Type
    
    Interface FieldGeometry
        Module Procedure init_FieldGeometryGen
        Module Procedure init_FieldGeometrySlab
    End Interface
    
    Type BeamRay
        ! Defines a ray, i.e., the quantity of interest
        ! when ray-tracing. It gives all of the information for which
        ! we ray-trace in the first place --- the path length
        ! through a given material, as well as addressing information.
        Integer                   :: q           ! Quadrature sdof index of this ray
        Real (KREAL), Allocatable :: pathlen (:) ! Path length this ray endures within each material ! (m)
    End Type
    
    Type ExternalBeam
        ! The actual implementation of a beam in the context of Boltzmann transport.
        ! Contains, most importantly, a set of type-bound procedures that are
        ! relied upon in order to construct usable sources derived from external beams,
        ! that can thus be fed to a Boltzmann operator for a solution
        Logical,             Allocatable :: quadmask (:)   ! Tells if a quadrature point is in the beam ! (qdof)
        Logical,             Allocatable :: elemmask (:)   ! Tells if an element is in the beam         ! (e)
        Real (KREAL)                     :: n = ONE        ! Number of particles in this beam
        Real (KREAL),        Allocatable :: phi0s    (:)   ! Uncollided fluence, spatial profile ONLY   ! (qdof)
        Character (LEN=:),   Allocatable :: particle       ! Name of particle generated by this beam ! Is this actually useful? Leaving it in for user-friendliness
        Type (MeshClass),    Pointer     :: mesh
        Type (AngularClass), Pointer     :: angular
        Type (FieldGeometry)             :: fldgeo
        Type (BeamRay),      Allocatable :: rays     (:)   ! Rays, generated via self%RayTrace, that can be used to construct a primary angular fluence if desired
    Contains
        Procedure :: Populate
        Procedure :: GenerateENSRCFile
        Procedure :: RayTrace
        Procedure :: PrepFluence       ! Mostly internal routine for preparing the spatial part of the fluence map for fluence quad
        Procedure :: FluenceQuadrature ! Mostly internal routine, gives the fluence at mesh quadrature points
        Procedure :: AddAngularFluence ! A subroutine that adds the (uncollided) angular fluence on the real mesh. I hate it
        Procedure :: Source  => FCSSource ! Rename to AddSource? That's what it does...
        Procedure :: Destroy => DestroyBeam
    End Type
    
    Interface ExternalBeam
        Module Procedure init_ExternalBeam
    End Interface
    
    Integer                   :: Lcoeff      ! Also private
    Real (KREAL), Allocatable :: coeff (:,:) ! Private so no concern about naming and such
    
